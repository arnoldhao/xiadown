package service

import (
	"errors"
	"fmt"
	"net/http"
	"net/url"
	"os"
	"strings"
	"time"

	"golang.org/x/net/http/httpguts"

	appytdlp "xiadown/internal/application/ytdlp"
)

const resourceCookieJarLifetime = 24 * time.Hour

var (
	errCapturedCookieHeaderInvalid   = errors.New("captured Cookie header does not contain a usable cookie")
	errCapturedHeaderAuthUnsupported = errors.New("captured header authentication is unsupported for external stream downloads")
)

// prepareCapturedCookieJar removes the browser Cookie header from the map that
// will become yt-dlp process arguments and writes those cookies to a random,
// operation-owned Netscape jar instead. A Cookie request header does not carry
// domain, path, expiry, or SameSite metadata, so the safest useful projection
// is the initial URL's exact host, root path, HTTPS-only when applicable, and a
// short expiry bounded by the operation's own cleanup.
func prepareCapturedCookieJar(rawURL string, headers map[string]string, now time.Time) (map[string]string, string, func(), error) {
	commandHeaders := make(map[string]string, len(headers))
	cookieHeader := http.Header{}
	for name, value := range headers {
		if strings.EqualFold(strings.TrimSpace(name), "Cookie") {
			if trimmed := strings.TrimSpace(value); trimmed != "" {
				cookieHeader.Add("Cookie", trimmed)
			}
			continue
		}
		normalizedName, normalizedValue, keep, err := normalizeCapturedYTDLPHeader(name, value)
		if err != nil {
			return commandHeaders, "", func() {}, err
		}
		if keep {
			commandHeaders[normalizedName] = normalizedValue
		}
	}
	cleanup := func() {}
	if len(cookieHeader.Values("Cookie")) == 0 {
		return commandHeaders, "", cleanup, nil
	}
	if err := appytdlp.ValidateNetworkURL(rawURL); err != nil {
		return commandHeaders, "", cleanup, fmt.Errorf("cannot scope captured cookies to download URL: %w", err)
	}
	parsed, err := url.Parse(strings.TrimSpace(rawURL))
	if err != nil {
		return commandHeaders, "", cleanup, fmt.Errorf("cannot scope captured cookies to download URL: %w", appytdlp.ErrUnsupportedNetworkURL)
	}
	host, ok := normalizedCapturedHostname(parsed.Hostname())
	if !ok {
		return commandHeaders, "", cleanup, fmt.Errorf("cannot scope captured cookies to download URL: %w", appytdlp.ErrUnsupportedNetworkURL)
	}

	cookies := uniqueValidCapturedCookies(cookieHeader)
	if len(cookies) == 0 {
		return commandHeaders, "", cleanup, errCapturedCookieHeaderInvalid
	}
	if now.IsZero() {
		now = time.Now()
	}
	expires := now.Add(resourceCookieJarLifetime).Unix()
	secure := "FALSE"
	if strings.EqualFold(parsed.Scheme, "https") {
		secure = "TRUE"
	}

	var payload strings.Builder
	payload.WriteString("# Netscape HTTP Cookie File\n")
	payload.WriteString("# Generated by XiaDown for one download operation.\n")
	for _, cookie := range cookies {
		_, _ = fmt.Fprintf(&payload, "%s\tFALSE\t/\t%s\t%d\t%s\t%s\n", host, secure, expires, cookie.Name, cookie.Value)
	}

	file, err := os.CreateTemp("", "xiadown-resource-cookies-*.txt")
	if err != nil {
		return commandHeaders, "", cleanup, fmt.Errorf("create temporary cookie jar: %w", err)
	}
	path := file.Name()
	remove := func() { _ = os.Remove(path) }
	if err := restrictResourceCookieJar(file); err != nil {
		_ = file.Close()
		remove()
		return commandHeaders, "", cleanup, fmt.Errorf("secure temporary cookie jar: %w", err)
	}
	if _, err := file.WriteString(payload.String()); err != nil {
		_ = file.Close()
		remove()
		return commandHeaders, "", cleanup, fmt.Errorf("write temporary cookie jar: %w", err)
	}
	if err := file.Close(); err != nil {
		remove()
		return commandHeaders, "", cleanup, fmt.Errorf("close temporary cookie jar: %w", err)
	}
	return commandHeaders, path, remove, nil
}

func normalizeCapturedYTDLPHeader(name string, value string) (string, string, bool, error) {
	normalizedName := strings.ToLower(strings.TrimSpace(name))
	trimmedValue := strings.TrimSpace(value)
	if normalizedName == "" || trimmedValue == "" || !httpguts.ValidHeaderFieldValue(trimmedValue) {
		return "", "", false, nil
	}
	if isProxyCredentialHeader(normalizedName) || normalizedName == "cookie2" {
		return "", "", false, nil
	}
	if isCapturedHeaderAuthentication(normalizedName) {
		return "", "", false, errCapturedHeaderAuthUnsupported
	}
	switch normalizedName {
	case "user-agent":
		return "User-Agent", trimmedValue, true, nil
	case "accept":
		return "Accept", trimmedValue, true, nil
	case "accept-language":
		return "Accept-Language", trimmedValue, true, nil
	case "referer":
		origin, ok := normalizedCapturedHTTPOrigin(trimmedValue)
		if !ok {
			return "", "", false, nil
		}
		return "Referer", origin + "/", true, nil
	case "origin":
		origin, ok := normalizedCapturedHTTPOrigin(trimmedValue)
		if !ok {
			return "", "", false, nil
		}
		return "Origin", origin, true, nil
	default:
		return "", "", false, nil
	}
}

func isCapturedHeaderAuthentication(name string) bool {
	normalized := strings.ToLower(strings.TrimSpace(name))
	switch normalized {
	case "authorization", "authentication", "api-key":
		return true
	}
	return strings.HasPrefix(normalized, "x-") ||
		strings.Contains(normalized, "auth-token") ||
		strings.Contains(normalized, "access-token") ||
		strings.Contains(normalized, "session-token")
}

func uniqueValidCapturedCookies(headers http.Header) []*http.Cookie {
	request := &http.Request{Header: headers}
	parsed := request.Cookies()
	result := make([]*http.Cookie, 0, len(parsed))
	seen := make(map[string]struct{}, len(parsed))
	for _, cookie := range parsed {
		if cookie == nil || strings.HasPrefix(cookie.Name, "$") {
			continue
		}
		candidate := &http.Cookie{Name: cookie.Name, Value: cookie.Value}
		if candidate.Valid() != nil {
			continue
		}
		if _, ok := seen[candidate.Name]; ok {
			continue
		}
		seen[candidate.Name] = struct{}{}
		result = append(result, candidate)
	}
	return result
}

func scopeCapturedRequestHeaders(headers map[string]string, initialURL string, targetURL string) map[string]string {
	result := make(http.Header, len(headers))
	for name, value := range headers {
		result.Set(name, value)
	}
	initial, _ := url.Parse(strings.TrimSpace(initialURL))
	target, _ := url.Parse(strings.TrimSpace(targetURL))
	scopeCapturedHTTPHeaders(result, initial, target)
	flattened := make(map[string]string, len(result))
	for name, values := range result {
		if len(values) > 0 {
			flattened[name] = values[0]
		}
	}
	return flattened
}
